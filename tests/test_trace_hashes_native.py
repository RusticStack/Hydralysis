"""The Rust port of trace_hashes (crates/hy-trace, bound in native/src/trace/hashes.rs) against the Python module.

Both implementations get the same inputs: primitives on generated bytes, the registry with profile codecs, dictionaries built
from the same names (ASCII, accented, astral, repeated, colliding), digests and interpretation revisions, the constant
scan over a synthetic image. Python is the specification; the Rust answers must equal it.
"""

import contextlib
import hashlib
import os
import random
import struct
import sys
import unittest
from pathlib import Path
from types import SimpleNamespace

sys.path.insert(0, str(Path(__file__).resolve().parent))

from hydralysis import trace_hashes, trace_native
from hydralysis.trace_hashes import Dictionary, HashError, Registry


@contextlib.contextmanager
def impl(value):
    """Run with HYDRALYSIS_IMPL set to VALUE ("" is the Python implementation)."""
    saved = os.environ.get("HYDRALYSIS_IMPL")
    os.environ["HYDRALYSIS_IMPL"] = value
    try:
        yield
    finally:
        if saved is None:
            os.environ.pop("HYDRALYSIS_IMPL", None)
        else:
            os.environ["HYDRALYSIS_IMPL"] = saved


def have_native():
    with impl("rust"):
        return trace_native.native() is not None


@unittest.skipUnless(have_native(), "hydralysis_native with the trace port is not built")
class RustMatchesPython(unittest.TestCase):
    NAMES = ["Player", "Enemy", "Weapon", "Door", "Inventory", "player", "café", "テスト", "a b", "x" * 300,
             "\U0001f600 face", "tab\there", "Straße", "İstanbul", "dot.ted.name", "under_score"]

    def both(self, function):
        with impl(""):
            python = function()
        with impl("rust"):
            native = function()
        return python, native

    def test_primitives_agree_on_generated_bytes(self):
        rng = random.Random(7)
        samples = [b"", b"a", b"abc", b"123456789", bytes(range(256))] + [rng.randbytes(rng.randrange(0, 70)) for _ in range(60)]
        for data in samples:
            for call in (lambda d: trace_hashes.fnv(d, 32), lambda d: trace_hashes.fnv(d, 64), lambda d: trace_hashes.fnv(d, 32, variant="1"),
                         lambda d: trace_hashes.fnv(d, 64, variant="1"),
                         lambda d: trace_hashes.fnv(d, 32, basis=0x12345678, prime=0x01000193),
                         lambda d: trace_hashes.fnv(d, 64, basis=0x1_0000_0000, prime=3),
                         trace_hashes.crc_generic, lambda d: trace_hashes.crc_generic(d, width=16, poly=0x1021, init=0xFFFF, xorout=0, refin=False, refout=False),
                         lambda d: trace_hashes.crc_generic(d, width=64, poly=0x42F0E1EBA9EA3693, init=0, xorout=0, refin=False, refout=False),
                         lambda d: trace_hashes.crc_generic(d, width=8, poly=7, init=0, xorout=0, refin=True, refout=False),
                         lambda d: trace_hashes.murmur3_32(d), lambda d: trace_hashes.murmur3_32(d, 0x9747B28C),
                         lambda d: trace_hashes.murmur3_32(d, 2 ** 40 + 5)):
                python, native = self.both(lambda: call(data))
                self.assertEqual(python, native, data)

    def test_the_same_errors_come_out(self):
        for call in (lambda: trace_hashes.fnv(b"x", 16), lambda: trace_hashes.fnv(b"x", 32, variant="2"),
                     lambda: trace_hashes.crc_generic(b"x", width=7), lambda: trace_hashes.crc_generic(b"x", width=65)):
            seen = []
            for value in ("", "rust"):
                with impl(value):
                    with self.assertRaises(HashError) as caught:
                        call()
                    seen.append((caught.exception.code, str(caught.exception)))
            self.assertEqual(seen[0], seen[1])

    def test_builtin_algorithms_agree_on_text_and_bytes(self):
        for name in Registry().names():
            for text in self.NAMES + [""]:
                python, native = self.both(lambda: Registry().compute(name, text))
                self.assertEqual(python, native, (name, text))
            python, native = self.both(lambda: Registry().compute(name, b"\x00\xffabc"))
            self.assertEqual(python, native)

    CODECS = [
        {"id": "fold64", "base": "fnv1a", "bits": 64, "fold": "lower", "vectors": [{"input": "A", "output": "0xaf63dc4c8601ec8c"}]},
        {"id": "wide32", "base": "fnv1", "bits": 32, "encoding": "utf-16le", "fold": "upper",
         "params": {"basis": "0x12345678", "prime": "0x01000193"}, "vectors": [{"input": "", "output": "0x12345678"}]},
        {"id": "crc16", "base": "crc", "bits": 16, "params": {"poly": "0x1021", "init": "0xffff", "xorout": 0, "refin": False, "refout": False},
         "vectors": [{"input": "123456789", "output": "0x29b1"}]},
        {"id": "lat", "base": "murmur3_32", "encoding": "latin-1", "params": {"seed": "0x9747b28c"},
         "vectors": [{"input": "The quick brown fox jumps over the lazy dog", "output": "0x2fa826cd"}]},
    ]

    def codec_registry(self):
        registry = Registry()
        for codec in self.CODECS:
            registry.add_codec(codec)
        return registry

    def test_profile_codecs_agree(self):
        for codec in self.CODECS:
            for text in self.NAMES[:8] + ["", "ABC"]:
                def run():
                    try:
                        return self.codec_registry().compute(codec["id"], text)
                    except (HashError, UnicodeEncodeError) as error:
                        return type(error).__name__
                python, native = self.both(run)
                self.assertEqual(python, native, (codec["id"], text))

    def test_bad_codecs_are_refused_the_same_way(self):
        bad = [{**self.CODECS[0], "id": "x1", "vectors": []}, {**self.CODECS[0], "id": "x2", "vectors": [{"input": "A", "output": "0x1"}]},
               {**self.CODECS[0], "id": "fnv1a64"}, {**self.CODECS[0], "id": "x3", "base": "sha1"}, {**self.CODECS[0], "id": "X4"},
               {**self.CODECS[2], "id": "x5", "bits": 7}, {**self.CODECS[0], "id": "x6", "bits": 16}]

        def run(codec):
            try:
                Registry().add_codec(codec)
                return "ok"
            except HashError as error:
                return (error.code, str(error))
        for codec in bad:
            python, native = self.both(lambda: run(codec))
            self.assertEqual(python, native, codec)

    def dictionary(self, algorithms=("fnv1a64", "fnv1a32", "crc32", "murmur3_32")):
        dictionary = Dictionary(self.codec_registry(), algorithms=list(algorithms))
        dictionary.add_lines("\n".join(self.NAMES[:6]) + "\n# comment\n\n  spaced name  \n", "fixture word list")
        dictionary.add_manifest(["data/archive/Items.tbl", "data\\archive\\Spells.tbl", "noext"], "archive manifest")
        for index, name in enumerate(self.NAMES):
            dictionary.add(name, "source %d" % (index % 3))
            dictionary.add(name, "source 0")
        return dictionary

    def test_dictionaries_answer_alike(self):
        def run():
            dictionary = self.dictionary()
            registry = dictionary.registry
            rows = []
            for name in self.NAMES + ["spaced name", "Items", "Items.tbl", "Spells", "nothing"]:
                for algorithm in dictionary.algorithms:
                    rows.append(dictionary.resolve(algorithm, registry.compute(algorithm, name)))
            rows.append(dictionary.resolve("crc32", "0x1234"))
            return {"len": len(dictionary), "rows": rows, "digest": dictionary.digest(), "collisions": dictionary.collisions(),
                    "sources": dictionary.sources}
        python, native = self.both(run)
        self.assertEqual(python, native)
        with impl("rust"):
            self.assertIsNotNone(self.dictionary()._native, "the dictionary should live in Rust")

    def test_a_dictionary_with_repeated_algorithms_digests_alike(self):
        def run():
            dictionary = Dictionary(algorithms=["fnv1a64", "crc32", "fnv1a64"])
            dictionary.add("one", "s")
            return dictionary.digest(), dictionary.resolve("fnv1a64", 5)
        python, native = self.both(run)
        self.assertEqual(python, native)

    def test_refusals_are_the_same(self):
        def run():
            dictionary = Dictionary(algorithms=["fnv1a64"])
            seen = []
            for call in (lambda: dictionary.add("x", " "), lambda: dictionary.add("x", "\x1c"), lambda: dictionary.add("", "s"),
                         lambda: dictionary.add("a\0b", "s"), lambda: dictionary.add("n" * 513, "s"), lambda: dictionary.add(5, "s"),
                         lambda: dictionary.add("x", None), lambda: dictionary.resolve("nope", 1), lambda: dictionary.resolve("fnv1a64", "zz"),
                         lambda: dictionary.resolve("fnv1a64", -1), lambda: dictionary.resolve("fnv1a64", 1 << 64),
                         lambda: dictionary.resolve("fnv1a64", True), lambda: dictionary.add_lines("ok\n" + "n" * 600, "s")):
                try:
                    call()
                    seen.append("ok")
                except HashError as error:
                    seen.append((error.code, str(error)))
            seen.append(len(dictionary))
            return seen
        python, native = self.both(run)
        self.assertEqual(python, native)

    def test_a_forced_collision_is_ambiguous_in_both(self):
        def run():
            registry = self.codec_registry()
            seen, pair = {}, None
            for index in range(5000):
                name = hashlib.sha256(str(index).encode()).hexdigest()[:12]
                value = registry.compute("crc16", name)
                if value in seen:
                    pair = (seen[value], name, value)
                    break
                seen[value] = name
            dictionary = Dictionary(registry, algorithms=["crc16"])
            dictionary.add(pair[0], "list one")
            dictionary.add(pair[1], "list two")
            return (dictionary.resolve("crc16", pair[2]), dictionary.collisions(),
                    trace_hashes.annotate_constants(dictionary, [{"value": pair[2], "where": "rva:0x1000"}]))
        python, native = self.both(run)
        self.assertEqual(python, native)
        self.assertEqual(native[0]["status"], "ambiguous")

    def test_annotation_and_interpretation_agree(self):
        def run():
            dictionary = self.dictionary(("fnv1a64", "fnv1a32", "crc32"))
            registry = dictionary.registry
            values = [registry.compute("fnv1a64", "Door"), 0x77, registry.compute("fnv1a64", "Enemy"), registry.compute("fnv1a64", "Door")]
            constants = [{"value": registry.compute("fnv1a64", "Enemy"), "where": "rva:0x1010"}, {"value": 0xDEAD, "where": "rva:0x2000"},
                         {"value": "0x%x" % registry.compute("fnv1a32", "Door")}, {"value": registry.compute("crc32", "Weapon")}]
            events = [{"event_id": "ev_1", "payload": {"record": values[0], "n": 3, "list": [1], "map": {}}},
                      {"event_id": "ev_2", "payload": {"record": 0x77}}, {"event_id": "ev_3", "payload": {"record": "0x%x" % values[2]}},
                      {"event_id": "ev_4"}, {"event_id": "ev_5", "payload": {}}, {"event_id": "ev_6", "payload": {"record": True}},
                      {"event_id": "ev_7", "payload": {"record": -4}}, {"event_id": "ev_8", "payload": {"record": 1.5}},
                      {"event_id": "ev_9", "payload": {"record": "junk"}}, {"payload": {"record": values[0]}}]
            out = {"annotate": trace_hashes.annotate_constants(dictionary, constants),
                   "annotate_named": trace_hashes.annotate_constants(dictionary, constants, ["fnv1a64"]),
                   "interpretation": trace_hashes.interpretation(dictionary, "fnv1a64", values, parent="hn_parent"),
                   "events": trace_hashes.interpret_events(dictionary, "fnv1a64", events, ["record", "absent"]),
                   "empty": trace_hashes.interpretation(dictionary, "nope", [])}
            dictionary.add("Window", "later list")
            out["changed"] = trace_hashes.interpret_events(dictionary, "fnv1a64", events, ["record"])
            return out
        python, native = self.both(run)
        self.assertEqual(python, native)
        self.assertTrue(python["events"]["interpretation"]["raw_preserved"])

