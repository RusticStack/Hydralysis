    def image(self):
        value = trace_hashes.fnv(b"Inventory", 64)
        other = trace_hashes.fnv(b"Door", 32)
        code = b"\x90" * 8 + b"\x48\xb8" + struct.pack("<Q", value) + b"\xc3" + struct.pack("<I", other) + b"\x90" * 8
        data = b"\x00" * 16 + struct.pack("<Q", value) + struct.pack("<Q", value)[1:] + b"\x00" * 4
        raw = code + data

        def section(name, rva, flags, start, size):
            return SimpleNamespace(Name=name.ljust(8, b"\0"), VirtualAddress=rva, PointerToRawData=start, SizeOfRawData=size, Characteristics=flags)

        def bounds(rva):
            if rva == 0x1005:
                raise ValueError("no pdata here")
            return (0x1000, 0x1020) if 0x1000 <= rva < 0x1020 else None
        return SimpleNamespace(data=raw, sections=[section(b".text", 0x1000, 0x60000020, 0, len(code)),
                                                   section(b".data", 0x2000, 0xC0000040, len(code), len(data)),
                                                   section(b".bad\xff", 0x3000, 0x40000040, len(raw) + 99, 10)], _bounds=bounds), value, other

    def test_the_constant_scan_agrees(self):
        image, value, other = self.image()
        for limit in (50, 1, 2, 3, 0):
            for functions in (None, [(0x1000, 0x1100)]):
                python, native = self.both(lambda: trace_hashes.scan_constants(image, [(value, 64), (other, 32), (0, 64)], limit=limit,
                                                                             functions=functions))
                self.assertEqual(python, native, (limit, functions))

    def test_the_name_search_agrees(self):
        image, value, _ = self.image()

        def run():
            dictionary = Dictionary(algorithms=["fnv1a64", "crc32"])
            dictionary.add("Inventory", "word list")
            return [trace_hashes.find_name_users(dictionary, "Inventory", image, algorithms=["fnv1a64"], limit=limit) for limit in (50, 1)]
        python, native = self.both(run)
        self.assertEqual(python, native)
        self.assertEqual(len(native[0]["hits"]), 2)

    def test_a_bulk_dictionary_agrees(self):
        rng = random.Random(3)
        names = ["".join(chr(rng.choice([rng.randrange(97, 123), rng.randrange(0xC0, 0x250), rng.randrange(0x4E00, 0x4E40)]))
                         for _ in range(rng.randrange(1, 20))) for _ in range(3000)]

        def run():
            dictionary = Dictionary(algorithms=["fnv1a64", "fnv1a32", "crc32", "murmur3_32"])
            dictionary.add_lines("\n".join(names), "bulk")
            probe = [dictionary.resolve("fnv1a32", dictionary.registry.compute("fnv1a32", name)) for name in names[:200]]
            return len(dictionary), dictionary.digest(), probe, dictionary.collisions()
        python, native = self.both(run)
        self.assertEqual(python, native)


